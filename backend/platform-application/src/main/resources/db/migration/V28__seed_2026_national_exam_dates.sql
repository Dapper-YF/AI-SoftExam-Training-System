INSERT INTO exam_region_schedule
  (region_code, region_name, exam_period_code, node_type, scheduled_at, note, status, created_at, updated_at)
SELECT r.region_code, r.region_code, p.exam_period_code, 'EXAM', p.scheduled_at, p.note, 'PUBLISHED', NOW(), NOW()
FROM (
  SELECT 'BJ' region_code UNION ALL SELECT 'TJ' UNION ALL SELECT 'HE' UNION ALL SELECT 'SX' UNION ALL SELECT 'NM'
  UNION ALL SELECT 'LN' UNION ALL SELECT 'JL' UNION ALL SELECT 'HL' UNION ALL SELECT 'SH' UNION ALL SELECT 'JS'
  UNION ALL SELECT 'ZJ' UNION ALL SELECT 'AH' UNION ALL SELECT 'FJ' UNION ALL SELECT 'JX' UNION ALL SELECT 'SD'
  UNION ALL SELECT 'HA' UNION ALL SELECT 'HB' UNION ALL SELECT 'HN' UNION ALL SELECT 'GD' UNION ALL SELECT 'GX'
  UNION ALL SELECT 'HI' UNION ALL SELECT 'CQ' UNION ALL SELECT 'SC' UNION ALL SELECT 'GZ' UNION ALL SELECT 'YN'
  UNION ALL SELECT 'XZ' UNION ALL SELECT 'SN' UNION ALL SELECT 'GS' UNION ALL SELECT 'QH' UNION ALL SELECT 'NX' UNION ALL SELECT 'XJ'
) r CROSS JOIN (
  SELECT '2026-H1' exam_period_code, '2026-05-23 08:00:00' scheduled_at, 'National exam date: 2026-05-23 to 2026-05-26' note
  UNION ALL SELECT '2026-H2', '2026-10-24 08:00:00', 'National exam date: 2026-10-24 to 2026-10-27'
) p;
